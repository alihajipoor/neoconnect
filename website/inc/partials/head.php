<?php
/**
 * Document head and the opening of the body. Every page includes this first
 * and inc/partials/footer.php last.
 *
 * Nothing here loads from another origin. Styles, script, fonts and images
 * are all this host's own -- a third-party request is slow at best and
 * blocked at worst on the networks this product exists for.
 *
 * PERFORMANCE SHAPE OF EVERY PAGE
 *   - The page's CSS is INLINED (base + blocks + the page's own module), so
 *     nothing blocks the first paint. It is allowed by its SHA-256 in the
 *     CSP, never by 'unsafe-inline'.
 *   - At most two font files are preloaded, per locale: exactly the faces
 *     the first screen paints.
 *   - One tiny inline script (hashed) flips no-js to js before the first
 *     paint and adds site.js asynchronously. Nothing on the site needs
 *     JavaScript to work.
 *   - No raster image above the fold; the art is HTML, CSS and one SVG.
 */

defined('NX') || exit;

require_once NX_INC . '/partials/icons.php';
require_once NX_INC . '/partials/world.php';

$nx_page = nx_page();

// A page may override its metadata by setting these before including this
// file -- the 404 page does, because it borrows the home page's navigation
// but is emphatically not the home page.
$nx_title = isset($NX_TITLE) ? $NX_TITLE : nx_t('meta.' . $nx_page . '.title');
$nx_description = isset($NX_DESCRIPTION)
    ? $NX_DESCRIPTION
    : nx_t('meta.' . $nx_page . '.description');

// Pages excluded from indexing (again, the 404) opt out here rather than
// having their URLs guessed at in robots.txt.
$nx_noindex = !empty($NX_NOINDEX);

// ---------------------------------------------------------------------
// Inline stylesheet and the loader, and the CSP that names both.
// ---------------------------------------------------------------------
$nx_css_modules = array('base', 'blocks');
if ($nx_page === 'home' && empty($NX_TITLE)) {
    $nx_css_modules[] = 'home';
}
if (in_array($nx_page, array('contact', 'reseller', 'delete-account'), true)) {
    $nx_css_modules[] = 'forms';
}
$nx_css = nx_css_bundle($nx_css_modules);

// The loader. Static apart from two values PHP fills in, and hashed below
// from the exact bytes emitted, so the CSP can never disagree with it.
//  - no-js -> js before the first paint: CSS can fold the mobile menu away
//    without a flash of it open, and without a layout shift.
//  - a dismissed announcement is hidden before the first paint, for the
//    same reason.
//  - site.js is added asynchronously ('strict-dynamic' trusts it because
//    this hashed script inserted it).
$nx_announce_key = 'nx-announce-' . nx_cfg('announcement_version', '1');
$nx_loader = '(function(d){var e=d.documentElement;e.className=e.className.replace(/\bno-js\b/,"js");'
    . 'try{if(localStorage.getItem(' . json_encode($nx_announce_key) . ')==="1")e.className+=" ann-off"}catch(x){}'
    . 'var s=d.createElement("script");s.src=' . json_encode(nx_asset('js/site.js'), JSON_UNESCAPED_SLASHES)
    . ';s.async=true;d.head.appendChild(s)})(document);';

nx_security_headers(nx_csp_for_page(
    array(base64_encode(hash('sha256', $nx_loader, true))),
    array(base64_encode(hash('sha256', $nx_css, true)))
));
if (!headers_sent()) {
    // Generated per request and varying on the language cookie: revalidate
    // every time, never sit in a shared cache.
    header('Cache-Control: no-cache, must-revalidate');
}

// ---------------------------------------------------------------------
// Font preloads. PER LOCALE, at most two, and only what the first screen
// paints. Preloading everything competes with the document itself for
// the first round trip, on exactly the connections where that is costly.
//
//   English  Inter Tight (the headline) and Inter (everything else).
//   Persian  Vazirmatn only -- it sets the whole Persian page, Latin
//            words included.
//
// Not nx_asset(): these URLs must match the @font-face URLs in base.css
// character for character, or the browser downloads each font twice.
// The file names carry a version instead of a ?v= stamp.
// ---------------------------------------------------------------------
$nx_base = nx_cfg('base_path', '/');
$nx_preload_fonts = nx_locale() === 'fa'
    ? array('vazirmatn-v2.woff2')
    : array('inter-tight-latin-v1.woff2', 'inter-latin-v1.woff2');

// One social card per language, generated by scripts/make-og-image.mjs in
// a real browser -- which shapes Persian correctly, so the Persian pages
// finally get a Persian card. Absolute URL and no ?v= stamp: scrapers cache
// by exact URL more or less forever; if the art changes, rename the file.
$nx_og_image = isset($NX_OG_IMAGE)
    ? $NX_OG_IMAGE
    : $nx_base . 'assets/img/og-' . (nx_locale() === 'fa' ? 'fa' : 'en') . '-v3.jpg';
$nx_og_image_abs = rtrim(nx_cfg('site_url', ''), '/') . $nx_og_image;

// The theme. A visitor who used the switch has a cookie, and the server
// paints that theme from the first byte: data-theme on <html>, one
// theme-color, one color-scheme. Without the cookie there is no attribute
// and CSS follows the system (prefers-color-scheme). Either way there is no
// flash of the wrong theme and no script involved in getting it right.
$nx_theme = nx_theme();
$nx_theme_colors = array('light' => '#F1F3F6', 'dark' => '#090B12');
?>
<!doctype html>
<html lang="<?php echo nx_esc(nx_locale()); ?>" dir="<?php echo nx_esc(nx_dir()); ?>" class="no-js"<?php
    echo $nx_theme !== '' ? ' data-theme="' . $nx_theme . '"' : ''; ?>>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title><?php echo nx_esc($nx_title); ?></title>
<meta name="description" content="<?php echo nx_esc($nx_description); ?>">
<?php foreach ($nx_preload_fonts as $nx_f): ?>
<link rel="preload" href="<?php echo nx_esc($nx_base . 'assets/fonts/' . $nx_f); ?>" as="font" type="font/woff2" crossorigin>
<?php endforeach; ?>
<style><?php echo $nx_css; ?></style>
<script><?php echo $nx_loader; ?></script>
<?php if ($nx_theme !== ''): ?>
<meta name="color-scheme" content="<?php echo $nx_theme; ?>">
<meta name="theme-color" content="<?php echo $nx_theme_colors[$nx_theme]; ?>">
<?php else: ?>
<meta name="color-scheme" content="light dark">
<meta name="theme-color" content="<?php echo $nx_theme_colors['light']; ?>" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="<?php echo $nx_theme_colors['dark']; ?>" media="(prefers-color-scheme: dark)">
<?php endif; ?>
<?php if ($nx_noindex): ?>
<meta name="robots" content="noindex, follow">
<?php else: ?>
<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">
<link rel="canonical" href="<?php echo nx_esc(nx_abs_url($nx_page)); ?>">
<?php
// The two locales are the same page; x-default points at English so an
// unmatched language lands somewhere sensible. Reciprocal by construction.
foreach (array('en', 'fa') as $nx_alt): ?>
<link rel="alternate" hreflang="<?php echo $nx_alt; ?>" href="<?php echo nx_esc(nx_abs_url($nx_page, $nx_alt)); ?>">
<?php endforeach; ?>
<link rel="alternate" hreflang="x-default" href="<?php echo nx_esc(nx_abs_url($nx_page, 'en')); ?>">
<?php endif; ?>
<meta property="og:type" content="website">
<meta property="og:site_name" content="<?php echo nx_e('brand.name'); ?>">
<meta property="og:title" content="<?php echo nx_esc($nx_title); ?>">
<meta property="og:description" content="<?php echo nx_esc($nx_description); ?>">
<meta property="og:url" content="<?php echo nx_esc(nx_abs_url($nx_page)); ?>">
<meta property="og:locale" content="<?php echo nx_locale() === 'fa' ? 'fa_IR' : 'en_US'; ?>">
<meta property="og:locale:alternate" content="<?php echo nx_locale() === 'fa' ? 'en_US' : 'fa_IR'; ?>">
<meta property="og:image" content="<?php echo nx_esc($nx_og_image_abs); ?>">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:type" content="image/jpeg">
<meta property="og:image:alt" content="<?php echo nx_e('meta.og.image_alt'); ?>">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="<?php echo nx_esc($nx_title); ?>">
<meta name="twitter:description" content="<?php echo nx_esc($nx_description); ?>">
<meta name="twitter:image" content="<?php echo nx_esc($nx_og_image_abs); ?>">
<meta name="twitter:image:alt" content="<?php echo nx_e('meta.og.image_alt'); ?>">
<link rel="icon" href="<?php echo nx_esc(nx_asset('img/favicon.svg')); ?>" type="image/svg+xml">
<link rel="icon" href="<?php echo nx_esc(nx_asset('img/favicon-32.png')); ?>" sizes="32x32" type="image/png">
<link rel="apple-touch-icon" href="<?php echo nx_esc(nx_asset('img/apple-touch-icon.png')); ?>">
<?php
// Structured data, last in the head so it can read anything set above it.
// A noindex page gets none: describing a page to a search engine while
// telling it not to index that page is a contradiction.
if (!$nx_noindex) {
    require_once NX_INC . '/partials/schema.php';
    nx_render_schema();
}
?>
</head>
<body>
<a class="skip-link" href="#main"><?php echo nx_e('skip_to_content'); ?></a>
<?php echo nx_logo_sprite(); ?>
<div class="sky" aria-hidden="true"><i class="sky__a"></i><i class="sky__b"></i><i class="sky__c"></i></div>
<?php require NX_INC . '/partials/header.php'; ?>
<main id="main">
